for (const [width, height] of [[360, 800], [390, 844], [430, 932], [768, 1024], [1280, 900], [1920, 1080]]) {
  test(`command surfaces fit ${width}×${height}, with readable labels and unobstructed actions`, async ({ browser }) => {
    const context = await browser.newContext({ viewport: { width, height }, isMobile: width < 821, hasTouch: width < 821 })
    const page = await context.newPage()
    try {
      await importTestArmy(page)
      const { ffa } = await seedDesignBattles(page)
      await page.goto(`/battle/${ffa}`)
      for (const panel of ['overview', 'army', 'objectives', 'cards', 'log', 'report'] as const) {
        await selectPanel(page, panel)
        expect(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth), panel).toBe(false)
        const actions = await page.locator('.battle-tabs').getByRole('button').evaluateAll((buttons) => buttons.map((button) => ({ height: button.getBoundingClientRect().height, width: button.getBoundingClientRect().width })))
        expect(actions.every((button) => button.height >= 44 && button.width >= 44)).toBe(true)
        await expect(page.locator('.next-phase')).toBeInViewport()
        if (panel === 'overview') {
          const cpButtons = await page.locator('.score-card .compact-controls button').evaluateAll((buttons) => buttons.map((button) => ({ width: button.getBoundingClientRect().width, height: button.getBoundingClientRect().height })))
          expect(cpButtons.length).toBeGreaterThan(0)
          expect(cpButtons.every((button) => button.width >= 44 && button.height >= 44)).toBe(true)
          const centre = await page.locator('.context-centre:visible').boundingBox()
          const heading = await page.locator('.context-centre__heading:visible').boundingBox()
          const item = await page.locator('.context-item:visible').first().boundingBox()
          expect(heading!.y - centre!.y).toBeLessThanOrEqual(24)
          expect(heading!.y + heading!.height).toBeLessThanOrEqual(item!.y)
        }
        if (panel === 'cards') {
          const counts = await page.locator('.official-secondary-panel:visible .secondary-deck-counts').boundingBox()
          expect(counts!.height).toBeLessThan(80)
        }
      }
      await selectPanel(page, 'objectives')
      const boxes = await page.locator('.objective-label').evaluateAll((labels) => labels.map((label) => label.getBoundingClientRect().toJSON()))
      for (const [index, box] of boxes.entries()) for (const other of boxes.slice(index + 1)) expect(box.right <= other.left || box.left >= other.right || box.bottom <= other.top || box.top >= other.bottom).toBe(true)
      await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight))
      const last = page.locator('.battlefield-table-note').locator('..').locator('..')
      const lastBox = await last.boundingBox()
      const navBox = await page.locator('.battle-tabs').boundingBox()
      if (width < 821) expect(lastBox!.y + lastBox!.height).toBeLessThanOrEqual(navBox!.y)
    } finally { await context.close() }
  })
}
