test('live combat feedback remains compact and opens Chronicle without replaying after reload', async ({ browser }) => {
  const { context, page } = await phone(browser)
  try {
    await importTestArmy(page)
    const { ffa } = await seedDesignBattles(page)
    await page.goto(`/battle/${ffa}`)
    await expect(page.locator('.score-card')).toHaveCount(3)
    await page.evaluate(async () => {
      const { useBattleStore } = await import('/src/stores/battleStore.ts')
      const store = useBattleStore.getState()
      const session = store.session!
      const target = Object.keys(session.state.players['p-b'].units)[0]
      const attacker = Object.keys(session.state.players['p-a'].units)[0]
      store.dispatch({ type: 'UNIT_DESTROYED', payload: { playerId: 'p-b', unitId: target, destroyedByPlayerId: 'p-a', attackerUnitId: attacker } })
    })
    const notice = page.locator('.battle-kill-notice')
    await expect(notice).toBeVisible()
    const noticeBox = await notice.boundingBox()
    const navigationBox = await page.locator('.battle-tabs').boundingBox()
    expect(noticeBox!.height).toBeLessThan(160)
    expect(noticeBox!.y + noticeBox!.height).toBeLessThanOrEqual(navigationBox!.y)
    await notice.getByRole('button', { name: 'Chronicle', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Battle Chronicle', exact: true })).toBeVisible()
    await expect(page.locator('.chronicle-entry--kills')).not.toHaveCount(0)
    await page.reload()
    await expect(page.locator('.battle-kill-notice')).toHaveCount(0)
    await expect(page.locator('.live-score-pulse')).toHaveCount(0)
  } finally { await context.close() }
})

