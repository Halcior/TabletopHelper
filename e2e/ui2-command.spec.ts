test('mobile navigation, CP keyboard control, card drafts, editor drafts and read-only Replay', async ({ browser }) => {
  const { context, page } = await phone(browser)
  try {
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await importTestArmy(page)
    const { ffa } = await seedDesignBattles(page)
    await page.goto(`/battle/${ffa}`)
    const navigation = page.getByRole('navigation', { name: 'Battle panels' })
    await expect(navigation.getByRole('button')).toHaveCount(5)
    await expect(navigation.getByRole('button')).toHaveText(['Battle', 'Army', 'Objectives', 'Cards', 'More'])
    await expect(page.locator('.live-score-pulse')).toHaveCount(0)
    const cp = page.getByLabel(/^Command points for Custodes:/)
    const gainCp = page.getByRole('button', { name: 'Gain 1 CP for Custodes' })
    await expect(gainCp).toBeVisible()
    await gainCp.focus()
    await page.keyboard.press('Enter')
    await expect(cp).toHaveAccessibleName('Command points for Custodes: 6 CP')
    await expect(gainCp).toBeFocused()
    await page.getByRole('button', { name: 'Spend 1 CP for Custodes' }).click()
    await expect(cp).toHaveAccessibleName('Command points for Custodes: 5 CP')
    await expect(page.getByRole('dialog', { name: 'Command points for Custodes', exact: true })).toHaveCount(0)

    await selectPanel(page, 'cards')
    const cards = page.locator('.official-secondary-panel:visible')
    const plunder = cards.locator('.secondary-card').filter({ has: page.getByRole('heading', { name: 'Plunder', exact: true }) })
    await expect(plunder.getByText('Mission Action available', { exact: true })).toBeVisible()
    const firstUnit = await plunder.getByLabel('Acting unit').locator('option').nth(1).getAttribute('value')
    await plunder.getByLabel('Acting unit').selectOption(firstUnit!)
    await plunder.getByPlaceholder('Location on the table').fill('North ruin')
    await selectPanel(page, 'army')
    await selectPanel(page, 'cards')
    await expect(plunder.getByLabel('Acting unit')).toHaveValue(firstUnit!)
    await expect(plunder.getByPlaceholder('Location on the table')).toHaveValue('North ruin')

    await selectPanel(page, 'objectives')
    const center = page.locator('.objective-node[data-objective-id="CENTER"]')
    await center.click()
    await page.getByRole('dialog', { name: 'Objective controls for CENTER', exact: true }).getByRole('button', { name: 'Shield Host', exact: true }).click()
    await expect(center).toHaveAttribute('data-controller-id', 'p-b')
    expect(await center.evaluate((element) => getComputedStyle(element).borderTopColor)).toBe('rgb(103, 168, 213)')
    expect(await center.locator('.objective-node__symbol').evaluate((element) => getComputedStyle(element).animationName)).toBe('none')
    await page.getByRole('button', { name: 'Edit Layout', exact: true }).click()
    await page.getByLabel('Field width (cm)', { exact: true }).fill('160')
    await selectPanel(page, 'army')
    await selectPanel(page, 'objectives')
    await expect(page.getByLabel('Field width (cm)', { exact: true })).toHaveValue('160')
    await navigation.getByRole('button', { name: 'More', exact: true }).click()
    await expect(page.getByRole('menuitem', { name: 'Battle Replay', exact: true })).toBeDisabled()
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'Cancel layout edits' }).click()
    await navigation.getByRole('button', { name: 'More', exact: true }).click()
    await page.keyboard.press('ArrowDown')
    await expect(page.getByRole('menuitem', { name: 'Battle Replay', exact: true })).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('button', { name: 'Return to live', exact: true })).toBeVisible()
    await center.click()
    await expect(page.getByRole('dialog', { name: 'Objective controls for CENTER', exact: true }).getByRole('button', { name: 'Custodes', exact: true })).toBeDisabled()
    await page.keyboard.press('Escape')
    await page.reload()
    await selectPanel(page, 'objectives')
    await expect(center).toHaveAttribute('data-controller-id', 'p-b')
    await expect(page.locator('.objective-node--live')).toHaveCount(0)
    await expect(page.locator('.battlefield-canvas')).toHaveAttribute('data-width-cm', '180')
  } finally { await context.close() }
})

