import { expect, test, type Page } from '@playwright/test'

async function sessionJson(page: Page) {
  return page.evaluate(async () => JSON.stringify((await import('/src/stores/battleStore.ts')).useBattleStore.getState().session))
}

test('PL/EN persists and Table Mode stays public, responsive and read-only', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/account')
  await page.getByLabel('Language', { exact: true }).selectOption('pl')
  await expect(page.locator('html')).toHaveAttribute('lang', 'pl')
  await expect(page.getByRole('heading', { name: 'Moje konto' })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Język', { exact: true })).toHaveValue('pl')
  await page.evaluate(async () => {
    const { createCauldronGame } = await import('/src/rulesets/cauldronFFA3/session.ts')
    const { testArmy } = await import('/src/rulesets/cauldronFFA3/cauldronTestUtils.ts')
    const { dispatchBattleEvent } = await import('/src/domain/battle/engine.ts')
    const { saveBattle } = await import('/src/persistence/database.ts')
    const { createBattleClock, clockConfig } = await import('/src/features/battleClock/model.ts')
    const armies = ['Custodes', 'Death Guard', 'Necrons'].map((faction, i) => ({ ...testArmy(`army-${i}`), faction }))
    const { OFFICIAL_SECONDARY_IDS } = await import('/src/rulesets/cauldronFFA3/officialSecondaryDefinitions.ts')
    const first = ['OFFICIAL_ASSASSINATION', 'OFFICIAL_NO_PRISONERS']
    const order = [...first, ...OFFICIAL_SECONDARY_IDS.filter(id => !first.includes(id))]
    let session = createCauldronGame({ gameId: 'presentation-test', guidanceLevel: 'fast', primaryDeck: 'chapter-approved-ffa', secondaryDeck: 'chapter-approved', armies,
      secondaryDeckOrders: Object.fromEntries(['p0', 'p1', 'p2'].map(id => [id, order])),
      players: armies.map((army, i) => ({ id: `p${i}`, name: ['Bartek', 'Karolina', 'Michał'][i], armyId: army.id, deploymentZone: 'ABC'[i], turnPosition: i + 1, operationalPlanId: 'WYNISZCZENIE', officialPrimaryId: ['battlefield-dominance', 'meatgrinder', 'outmanoeuvre'][i] })),
    })
    session = dispatchBattleEvent(session, { type: 'PHASE_CHANGED', payload: { phase: 'SHOOTING' } })
    session = dispatchBattleEvent(session, { type: 'UNIT_MODEL_DESTROYED', payload: { playerId: 'p1', unitId: 'infantry', amount: 1, destroyedByPlayerId: 'p0', note: 'PRIVATE NOTE sentinel' } })
    session.setup.battleClock = clockConfig('casual')
    session.battleClock = createBattleClock(session.setup, session.setup.battleClock, Date.now())
    localStorage.setItem('tabletophelper:battle-clock-help:v2', '1')
    await saveBattle(session)
  })
  await page.goto('/battle/presentation-test')
  await expect(page.locator('.current-rival').first()).toContainText('Bieżący rywal — Runda 1')
  await expect(page.locator('.secondary-scope__label').first()).toHaveText('Rywal karty: Death Guard — Karolina')
  await expect(page.getByRole('heading', { name: 'Assassination', exact: true }).first()).toBeVisible()
  await expect(page.locator('.battle-focus h2')).toHaveText('Faza strzelania')
  await expect(page.locator('.battle-clock')).toContainText('Pauza')
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await page.screenshot({ path: 'test-results/polish-battle-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 900 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await page.screenshot({ path: 'test-results/polish-battle-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 375, height: 812 })
  await page.getByLabel('Komu przekazać czas?').selectOption('p1')
  const before = await sessionJson(page)
  await page.getByRole('button', { name: 'Otwórz menu bitwy' }).click()
  await page.getByLabel('Język', { exact: true }).focus()
  await page.keyboard.press('Home')
  await expect(page.getByLabel('Język', { exact: true })).toHaveValue('pl')
  await page.keyboard.press('End')
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await expect(page.getByLabel('Language', { exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.locator('.secondary-scope__label').first()).toHaveText('Target Rival: Death Guard — Karolina')
  await expect(page.locator('.battle-clock')).toContainText('Paused')
  expect(await sessionJson(page)).toBe(before)
  await page.getByRole('button', { name: 'Open battle menu' }).click()
  await page.getByRole('menuitem', { name: 'Table Mode', exact: true }).click()
  await expect(page.getByLabel('Table Mode · read only', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Round 1 / 5 · SHOOTING' })).toBeVisible()
  await expect(page.getByLabel('Public scores')).toContainText('Karolina')
  await expect(page.locator('.table-mode')).not.toContainText('Assassination')
  await expect(page.locator('.table-mode')).not.toContainText('PRIVATE NOTE sentinel')
  await expect(page.getByRole('button', { name: 'Edit Layout' })).toHaveCount(0)
  await expect(page.locator('.next-phase')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Pass time', exact: false })).toHaveCount(0)
  await page.locator('.objective-node').first().click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.objective-control-popover')).toHaveCount(0)
  await page.evaluate(() => (document.activeElement as HTMLElement)?.blur())
  await page.keyboard.press('Space')
  expect(await sessionJson(page)).toBe(before)
  for (const width of [1440, 768, 375]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
    await page.screenshot({ path: `test-results/table-mode-${width}.png`, fullPage: true })
  }
  await page.getByRole('button', { name: 'Back to battle' }).click()
  await expect(page.getByRole('navigation', { name: 'Battle panels' })).toBeVisible()
  await page.reload()
  await expect(page.locator('.secondary-scope__label').first()).toHaveText('Target Rival: Death Guard — Karolina')
  expect(await sessionJson(page)).toBe(before)
  await page.getByRole('button', { name: 'Open battle menu' }).click()
  await page.getByLabel('Language', { exact: true }).selectOption('pl')
  await page.keyboard.press('Escape')
  for (let i = 0; i < 4; i += 1) await page.locator('.next-phase').click()
  await expect(page.getByRole('heading', { name: 'Podsumowanie tury', exact: true })).toBeVisible()
  await expect(page.locator('.secondary-scope__label').first()).toContainText('Death Guard — Karolina')
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await page.screenshot({ path: 'test-results/polish-turn-review-mobile.png', fullPage: true })
})
